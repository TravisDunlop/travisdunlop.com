#!/usr/bin/env node
// Secret Santa helper for travisdunlop.com/secret-santa
//
//   node tools/secret-santa.mjs draw
//       Draws a fresh random assignment and writes ONLY encrypted data to
//       secret-santa/assignments.js. The plaintext pairs never touch disk
//       and are never printed, so nobody (including the site owner) sees them.
//
//   node tools/secret-santa.mjs emails path/to/emails.json
//       emails.json looks like {"Ari": ["ari@gmail.com"], "Tom": ["tom@gmail.com"], ...}
//       Writes SHA-256 hashes of the emails into secret-santa/participants.js,
//       so the emails themselves are never published. Changing emails does NOT
//       change who got whom.

import { webcrypto as crypto, randomInt } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "secret-santa");

// Names shown on the site. Order doesn't matter.
const NAMES = ["Travis", "Ari", "Whitney", "Jeremiah", "Kathy", "Tom", "Judy"];

// Optional pairs who should never draw each other, e.g. [["Kathy","Tom"]].
// Both directions are excluded.
const EXCLUDE = [];

const ITERATIONS = 150000;
const enc = new TextEncoder();
const hex = (buf) => Buffer.from(buf).toString("hex");
const b64 = (buf) => Buffer.from(buf).toString("base64");

export function normalizeEmail(email) {
  let [user, domain] = email.trim().toLowerCase().split("@");
  if (domain === "googlemail.com") domain = "gmail.com";
  if (domain === "gmail.com") user = user.split("+")[0].replace(/\./g, "");
  return `${user}@${domain}`;
}

async function sha256Hex(s) {
  return hex(await crypto.subtle.digest("SHA-256", enc.encode(s)));
}

function allowed(giver, receiver) {
  if (giver === receiver) return false;
  return !EXCLUDE.some(([a, b]) => (a === giver && b === receiver) || (a === receiver && b === giver));
}

function drawPairs() {
  for (let attempt = 0; attempt < 100000; attempt++) {
    const hat = [...NAMES];
    for (let i = hat.length - 1; i > 0; i--) {
      const j = randomInt(i + 1);
      [hat[i], hat[j]] = [hat[j], hat[i]];
    }
    if (NAMES.every((g, i) => allowed(g, hat[i]))) {
      return new Map(NAMES.map((g, i) => [g, hat[i]]));
    }
  }
  throw new Error("No valid assignment exists with these exclusions.");
}

async function deriveKey(pepper, giver, salt) {
  const base = await crypto.subtle.importKey("raw", enc.encode(`${pepper}:${giver}`), "PBKDF2", false, ["deriveKey"]);
  return crypto.subtle.deriveKey(
    { name: "PBKDF2", hash: "SHA-256", salt, iterations: ITERATIONS },
    base, { name: "AES-GCM", length: 256 }, false, ["encrypt", "decrypt"]);
}

async function draw() {
  const pairs = drawPairs();
  // Sanity checks without revealing anything.
  const receivers = new Set(pairs.values());
  if (receivers.size !== NAMES.length) throw new Error("not a permutation");
  for (const [g, r] of pairs) if (!allowed(g, r)) throw new Error("invalid pair");

  const pepper = b64(crypto.getRandomValues(new Uint8Array(24)));
  const entries = {};
  for (const [giver, receiver] of pairs) {
    const salt = crypto.getRandomValues(new Uint8Array(16));
    const iv = crypto.getRandomValues(new Uint8Array(12));
    const key = await deriveKey(pepper, giver, salt);
    const ct = await crypto.subtle.encrypt({ name: "AES-GCM", iv }, key, enc.encode(receiver));
    const id = await sha256Hex(`${pepper}|id|${giver}`);
    entries[id] = { salt: b64(salt), iv: b64(iv), ct: b64(ct) };
  }
  pairs.clear();

  // Round-trip check: every entry decrypts to a valid, different name.
  for (const giver of NAMES) {
    const e = entries[await sha256Hex(`${pepper}|id|${giver}`)];
    const key = await deriveKey(pepper, giver, Buffer.from(e.salt, "base64"));
    const pt = new TextDecoder().decode(await crypto.subtle.decrypt(
      { name: "AES-GCM", iv: Buffer.from(e.iv, "base64") }, key, Buffer.from(e.ct, "base64")));
    if (!allowed(giver, pt) || !NAMES.includes(pt)) throw new Error("round-trip check failed");
  }

  const data = { version: 1, drawnAt: new Date().toISOString(), iterations: ITERATIONS, pepper, entries };
  writeFileSync(join(ROOT, "assignments.js"),
    "// Generated by tools/secret-santa.mjs draw. Encrypted on purpose: please don't peek!\n" +
    `window.SECRET_SANTA_DATA = ${JSON.stringify(data, null, 2)};\n`);
  console.log(`Drew ${NAMES.length} assignments (valid, nobody has themselves${EXCLUDE.length ? ", exclusions respected" : ""}).`);
  console.log("Wrote secret-santa/assignments.js. Assignments were not printed.");
}

async function emails(file) {
  const input = JSON.parse(readFileSync(file, "utf8"));
  const seen = new Map();
  const people = [];
  for (const name of NAMES) {
    const list = [].concat(input[name] || []);
    const hashes = [];
    for (const e of list) {
      const n = normalizeEmail(e);
      if (seen.has(n)) throw new Error(`${e} is listed for both ${seen.get(n)} and ${name}`);
      seen.set(n, name);
      hashes.push(await sha256Hex(n));
    }
    if (!hashes.length) console.warn(`warning: no email for ${name} yet`);
    people.push({ name, emailHashes: hashes });
  }
  writeFileSync(join(ROOT, "participants.js"),
    "// Generated by tools/secret-santa.mjs emails. Emails are stored as SHA-256 hashes.\n" +
    `window.SECRET_SANTA_PARTICIPANTS = ${JSON.stringify(people, null, 2)};\n`);
  console.log(`Wrote secret-santa/participants.js for ${people.filter((p) => p.emailHashes.length).length}/${NAMES.length} people.`);
}

const [cmd, arg] = process.argv.slice(2);
if (cmd === "draw") await draw();
else if (cmd === "emails" && arg) await emails(arg);
else { console.error("usage: secret-santa.mjs draw | emails <emails.json>"); process.exit(1); }
